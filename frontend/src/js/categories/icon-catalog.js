export const ICON_FILTERS = [['', 'Todos'], ['expense', 'Despesas'], ['income', 'Receitas'], ['investment', 'Investimentos']];
export function normalizeIconSearch(value) {
    return String(value ?? '').normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLocaleLowerCase('pt-BR').trim();
}
export function filterIcons(query = '', group = '') {
    const words = normalizeIconSearch(query).split(/\s+/).filter(Boolean);
    return ICON_CATALOG.filter(item => (!group || item.groups.includes(group))
        && words.every(word => normalizeIconSearch(`${item.label} ${item.keywords}`).split(/\s+/).some(term => term.startsWith(word))));
}
export function iconLabel(id) { return ICON_CATALOG.find(item => item.id === id)?.label || 'Etiqueta'; }
